#[cfg(test)]
mod tests {
    use super::*;

    fn sample_packet(payload: Vec<u8>, src_port: u16, dst_port: u16) -> PcapPacket {
        PcapPacket {
            ts_sec: 1_700_000_000,
            ts_usec: 0,
            src_addr: Ipv4Addr::new(127, 0, 0, 1),
            src_port,
            dst_addr: Ipv4Addr::new(127, 0, 0, 1),
            dst_port,
            payload,
        }
    }

    //fusa:test REQ-RTPS-058
    #[test]
    fn encode_then_decode_round_trips_one_packet() {
        let pkt = sample_packet(vec![0xDE, 0xAD, 0xBE, 0xEF], 17410, 17411);
        let bytes = encode_pcap_file(std::slice::from_ref(&pkt));
        let decoded = decode_pcap_file(&bytes).unwrap();
        assert_eq!(decoded, vec![pkt]);
    }

    //fusa:test REQ-RTPS-058
    #[test]
    fn encode_then_decode_round_trips_several_packets_in_order() {
        let pkts = vec![
            sample_packet(vec![0x01; 8], 17410, 17411),
            sample_packet(vec![0x02; 3], 27410, 27411),
            sample_packet(vec![], 100, 200), // empty payload is still valid
        ];
        let bytes = encode_pcap_file(&pkts);
        let decoded = decode_pcap_file(&bytes).unwrap();
        assert_eq!(decoded, pkts);
    }

    //fusa:test REQ-RTPS-058
    #[test]
    fn global_header_matches_expected_layout() {
        let bytes = encode_pcap_file(&[]);
        assert_eq!(bytes.len(), GLOBAL_HEADER_LEN);
        assert_eq!(&bytes[0..4], &PCAP_MAGIC_MICROS_LE.to_le_bytes());
        assert_eq!(&bytes[20..24], &LINKTYPE_RAW.to_le_bytes());
    }

    //fusa:test REQ-RTPS-058
    //fusa:test REQ-RTPS-009
    #[test]
    fn decode_rejects_truncated_global_header_without_panicking() {
        assert_eq!(
            decode_pcap_file(&[0u8; 10]),
            Err(PcapError::Truncated {
                expected: GLOBAL_HEADER_LEN,
                got: 10
            })
        );
    }

    //fusa:test REQ-RTPS-058
    //fusa:test REQ-RTPS-009
    #[test]
    fn decode_rejects_bad_magic_without_panicking() {
        let mut bytes = encode_pcap_file(&[]);
        bytes[0] = 0x00;
        assert_eq!(
            decode_pcap_file(&bytes),
            Err(PcapError::BadMagic { got: 0xa1b2c300 })
        );
    }

    //fusa:test REQ-RTPS-058
    //fusa:test REQ-RTPS-009
    #[test]
    fn decode_rejects_truncated_packet_record_without_panicking() {
        let pkt = sample_packet(vec![0xAA; 4], 1, 2);
        let mut bytes = encode_pcap_file(std::slice::from_ref(&pkt));
        bytes.truncate(bytes.len() - 2); // chop the last 2 payload bytes off
        assert!(matches!(
            decode_pcap_file(&bytes),
            Err(PcapError::Truncated { .. })
        ));
    }

    //fusa:test REQ-RTPS-058
    //fusa:test REQ-RTPS-009
    #[test]
    fn decode_rejects_non_ipv4_udp_record_without_panicking() {
        // A well-formed global header followed by one record whose "IPv4"
        // header claims IPv6 (version nibble 6) instead.
        let mut bytes = encode_pcap_file(&[]);
        let mut bogus_record = vec![0x65u8]; // version=6, not 4
        bogus_record.resize(IPV4_HEADER_LEN + UDP_HEADER_LEN, 0);
        let incl_len = bogus_record.len() as u32;
        bytes.extend_from_slice(&0u32.to_le_bytes()); // ts_sec
        bytes.extend_from_slice(&0u32.to_le_bytes()); // ts_usec
        bytes.extend_from_slice(&incl_len.to_le_bytes());
        bytes.extend_from_slice(&incl_len.to_le_bytes());
        bytes.extend_from_slice(&bogus_record);
        assert_eq!(
            decode_pcap_file(&bytes),
            Err(PcapError::NotIpv4Udp { index: 0 })
        );
    }
}
